#!/usr/bin/env python3
"""Write Cage87/Data.lean (the graph) and Cage87/Chunks.lean (the kernel checks) from the sparse6
file of the 8-regular graph of girth 7 on 768 vertices (Quantavane, 12 November 2026: the case
q = 7 of a construction from the generalized quadrangle W(7)).

Before writing anything the script checks the graph independently of the Lean code: simple,
768 vertices, every degree 8, and girth 7 by breadth-first search from every vertex; it also
finds the 7-cycle that the Lean proof uses. Nothing here is trusted by the Lean proof, which
checks the data itself.

Usage: make_data.py GRAPH.s6[.gz] OUTDIR
"""
import gzip, hashlib, sys
from collections import deque

S6_SHA256 = '95683e1cbf3169111cdb138e30264a8f92ce774e08c28004afa02c67830b3eae'  # uncompressed
N, K, CHUNK = 768, 8, 96
NS = 'Cage87'


def sparse6(raw):
    s = raw.strip()
    assert s.startswith(b':')
    data = [c - 63 for c in s[1:]]
    if data[0] < 63:
        n, data = data[0], data[1:]
    elif data[1] < 63:
        n = (data[1] << 12) + (data[2] << 6) + data[3]
        data = data[4:]
    else:
        raise ValueError('graph too large')
    k = 1
    while 1 << k < n:
        k += 1

    def stream():
        it = iter(data)
        d, dlen = 0, 0
        while True:
            if dlen < 1:
                try:
                    d = next(it)
                except StopIteration:
                    return
                dlen = 6
            dlen -= 1
            b = (d >> dlen) & 1
            x = d & ((1 << dlen) - 1)
            xlen = dlen
            while xlen < k:
                try:
                    d = next(it)
                except StopIteration:
                    return
                dlen = 6
                x = (x << 6) + d
                xlen += 6
            x >>= (xlen - k)
            dlen = xlen - k
            yield b, x

    v, edges = 0, []
    for b, x in stream():
        if b == 1:
            v += 1
        if x >= n or v >= n:
            break
        if x > v:
            v = x
        else:
            edges.append((x, v))
    return n, edges


def girth(adj):
    best = None
    for r in range(len(adj)):
        dist, par = {r: 0}, {r: -1}
        q = deque([r])
        while q:
            u = q.popleft()
            for w in adj[u]:
                if w not in dist:
                    dist[w], par[w] = dist[u] + 1, u
                    q.append(w)
                elif par[u] != w:
                    c = dist[u] + dist[w] + 1
                    if best is None or c < best[0]:
                        best = (c, r, u, w, dict(par))
    return best


def main():
    src, out = sys.argv[1], sys.argv[2]
    raw = open(src, 'rb').read()
    if src.endswith('.gz'):
        raw = gzip.decompress(raw)
    assert hashlib.sha256(raw).hexdigest() == S6_SHA256, 'unexpected graph file'
    n, edges = sparse6(raw)
    assert n == N
    adj = [set() for _ in range(n)]
    for a, b in edges:
        assert a != b, 'loop'
        assert b not in adj[a], 'repeated edge'
        adj[a].add(b)
        adj[b].add(a)
    assert all(len(s) == K for s in adj), 'not 8-regular'
    adj = [sorted(s) for s in adj]
    g = girth(adj)
    assert g[0] == 7, g[0]
    # the 7-cycle: root -> ... -> u, the edge u w, w -> ... -> root
    _, r, u, w, par = g

    def path(x):
        p = [x]
        while par[p[-1]] != -1:
            p.append(par[p[-1]])
        return p
    pu, pw = path(u), path(w)
    cyc = list(reversed(pu)) + pw[:-1]
    assert len(cyc) == 7 and len(set(cyc)) == 7 and cyc[0] == r
    assert all(cyc[(i + 1) % 7] in adj[cyc[i]] for i in range(7))
    # the branch condition checked in Lean, mirrored here
    for v in range(n):
        seen = set()
        for x in adj[v]:
            br = {x}
            for y in adj[x]:
                if y != v:
                    br.add(y)
                    br.update(z for z in adj[y] if z != x)
            assert not (br & seen), v
            seen |= br
    print(f'graph ok: {n} vertices, {len(edges)} edges, 8-regular, girth 7; a 7-cycle: {cyc}')

    with open(f'{out}/{NS}/Data.lean', 'w') as f:
        f.write('module\n\npublic import ' + NS + '.Check\n\n@[expose] public section\n\n')
        f.write('/-!\n# The graph\n\n')
        f.write('Generated by `scripts/make_data.py` from the sparse6 file of the graph (SHA-256 of the\n')
        f.write(f'uncompressed file `{S6_SHA256}`).\n')
        f.write('`adj` holds, for each vertex `0, …, 767`, its neighbours in increasing order, in a binary trie\n')
        f.write('of depth 10 (the leaf of `v` is reached by the bits of `v`, lowest first; the leaves past 767\n')
        f.write('are empty). This is data; the proof checks it.\n-/\n\n')
        f.write(f'namespace {NS}\n\n')
        f.write('set_option maxRecDepth 10000 in\n')
        f.write('/-- The neighbours of each vertex. -/\n')
        f.write('noncomputable def adj : Trie :=\n')

        def trie(depth, base, step):
            # vertices v = base (mod step), step = 2^(10 - depth)
            if depth == 0:
                lst = adj[base] if base < n else []
                return '(.leaf [' + ', '.join(map(str, lst)) + '])'
            return ('(.node ' + trie(depth - 1, base, step * 2) + '\n ' +
                    trie(depth - 1, base + step, step * 2) + ')')
        f.write(trie(10, 0, 1))
        f.write('\n\n')
        f.write(f'end {NS}\n')
    with open(f'{out}/{NS}/Chunks.lean', 'w') as f:
        f.write('module\n\npublic import ' + NS + '.Check\npublic import ' + NS + '.Data\n\n')
        f.write('@[expose] public section\n\n')
        f.write('/-!\n# The kernel checks\n\n')
        f.write(f'The branch check of every vertex, in {N // CHUNK} chunks of {CHUNK} vertices (generated by\n')
        f.write('`scripts/make_data.py`); each chunk is a separate kernel computation (`decide +kernel`).\n')
        f.write('`wf_ok` checks the adjacency lists.\n-/\n\n')
        f.write(f'namespace {NS}\n\n')
        f.write(f'theorem wf_ok : wfOk adj {N} {K} = true := by decide +kernel\n\n')
        for c in range(N // CHUNK):
            f.write(f'theorem chunk_{c} : verticesOk adj {c * CHUNK} {CHUNK} = true := by decide +kernel\n\n')
        f.write('/-- Every vertex passes the branch check. -/\n')
        f.write(f'theorem vertices_ok (v : Nat) (hv : v < {N}) : vertexOk adj v = true := by\n')
        cases = ' | '.join(f'h{c}' for c in range(N // CHUNK))
        f.write(f'  have : ' + ' ∨ '.join(f'({c * CHUNK} ≤ v ∧ v < {(c + 1) * CHUNK})' for c in range(N // CHUNK)) + ' := by omega\n')
        f.write(f'  rcases this with {cases}\n')
        for c in range(N // CHUNK):
            f.write(f'  · exact verticesOk_mem adj {c * CHUNK} {CHUNK} chunk_{c} v h{c}.1 (by omega)\n')
        f.write(f'\nend {NS}\n')


if __name__ == '__main__':
    main()
